import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const root=new URL("../cmd/entropy-server/web/",import.meta.url);
const context=vm.createContext({Uint8Array,URL,location:{href:"https://example.test/api-sources.html",protocol:"https:"}});
vm.runInContext(readFileSync(new URL("lab-samples.js",root),"utf8"),context);
const lab=context.EntropyLabSamples;
assert.deepEqual(Array.from(lab.pattern("00 ff 3a")),[0,255,58]);
for(const value of ["f","zz","","00".repeat(513)])assert.throws(()=>lab.pattern(value));
assert.deepEqual(Array.from(lab.generate("counter",4,{sequence:254})),[254,255,0,1]);
assert.deepEqual(Array.from(lab.generate("pattern",7,{sequence:2,bytes:Uint8Array.of(1,2,3)})),[3,1,2,3,1,2,3]);
assert.deepEqual(Array.from(lab.generate("constant",3,{value:128})),[128,128,128]);
assert.throws(()=>lab.generate("constant",3,{value:256}));assert.throws(()=>lab.generate("crypto",1048577));
const requests=[];
const crypto={getRandomValues(bytes){requests.push(bytes.length);bytes.fill(42);}};
const output=lab.generate("crypto",1048576,{crypto});
assert.equal(output.length,1048576);assert.equal(requests.length,16);assert.ok(requests.every(n=>n<=65536));assert.ok(output.every(n=>n===42));
const bytes=Uint8Array.of(0,1,127,128,254,255);
assert.deepEqual(Array.from(lab.transform(bytes,"lsb")),[0,255,255,0,0,255]);
assert.equal(lab.transform(bytes,"xor"),null);
assert.deepEqual(Array.from(lab.transform(bytes,"xor",bytes)),[0,0,0,0,0,0]);
const meter=new lab.Meter();meter.reset(100);meter.add(1000,110);assert.equal(meter.snapshot(120).bytesPerSecond,null);
meter.add(2000,310);let snapshot=meter.snapshot(600);assert.equal(snapshot.bytesPerSecond,6000);assert.equal(snapshot.meanIntervalMs,200);
meter.stop(1100);snapshot=meter.snapshot(9100);assert.equal(snapshot.bytesPerSecond,3000);assert.equal(snapshot.elapsedMs,1000);
assert.equal(lab.endpoint("/stream","http").href,"https://example.test/stream");
for(const [url,kind]of[["http://x.test","http"],["ws://x.test","websocket"],["https://u:p@x.test","http"],["file:///etc/passwd","http"],["https://x.test/#frag","http"]])assert.throws(()=>lab.endpoint(url,kind));
console.log("Lab generators, 64 KiB Web Crypto calls, transformations, meters and URL validation: passed");
