type HealthInfo struct {
	Status               string    `json:"status"`
	Ready                bool      `json:"ready"`
	Version              string    `json:"rng_version"`
	Source               string    `json:"rng_source"`
	DRBG                 string    `json:"rng_drbg"`
	ReseedAgeMs          int64     `json:"reseed_age_ms"`
	ReseedIntervalMs     int64     `json:"reseed_interval_ms"`
	ReseedSizeBits       int       `json:"reseed_size_bits"`
	MaxReseedAgeMs       int64     `json:"max_reseed_age_ms"`
	LastReseedAt         time.Time `json:"last_reseed_at"`
	ReseedFailuresTotal  uint64    `json:"reseed_failures_total"`
	LastReseedError      string    `json:"last_reseed_error,omitempty"`
	EntropyBufferEnabled bool      `json:"entropy_buffer_enabled"`
	EntropyBufferedBytes int       `json:"entropy_buffered_kb"`
	EntropyBufferedPCT   int       `json:"entropy_buffered_pct"`
}

// Count once at the HTTP boundary, including rejected requests and static files.
// Passing the original ResponseWriter preserves WebSocket upgrade support.
func countRequests(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		metrics.AddHTTPRequests(1)
		next.ServeHTTP(w, r)
	})
}

func reseedReady(meta drbg.Metadata, maxAge time.Duration) bool {
	return meta.LastReseedError == "" && meta.ReseedAge <= maxAge
}

// Liveness does not depend on the configured seed source being available.
func livenessHandler(w http.ResponseWriter, _ *http.Request) {
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", "no-store")
	_, _ = w.Write([]byte("{\"status\":\"ok\"}\n"))
}

func healthHandler(d *drbg.DRBG, maxAge time.Duration) http.HandlerFunc {
	return func(w http.ResponseWriter, _ *http.Request) {
		meta := d.GetMetadata()
		ready := reseedReady(meta, maxAge)

		status, code := "ok", http.StatusOK
		if !ready {
			status, code = "degraded", http.StatusServiceUnavailable
		}

		health := HealthInfo{
			Status: status, Ready: ready,
			Version: meta.Version, Source: meta.Source, DRBG: meta.DRBG,
			ReseedAgeMs:      meta.ReseedAge.Milliseconds(),
			ReseedIntervalMs: meta.ReseedIntervalMs, ReseedSizeBits: meta.ReseedSizeBits,
			MaxReseedAgeMs: maxAge.Milliseconds(), LastReseedAt: meta.LastReseedAt,
			ReseedFailuresTotal: meta.ReseedFailuresTotal, LastReseedError: meta.LastReseedError,
		}

		d.WriteHeaders(w)
		w.Header().Set("Content-Type", "application/json")
		w.Header().Set("Cache-Control", "no-store")
		w.WriteHeader(code)

		if err := json.NewEncoder(w).Encode(health); err != nil {
			log.Printf("encode health response: %v", err)
		}
	}
}

func metricsHandler(d *drbg.DRBG, maxAge time.Duration) http.HandlerFunc {
	const (
		counterType = "counter"
		gaugeType   = "gauge"
	)

	return func(w http.ResponseWriter, _ *http.Request) {
		meta := d.GetMetadata()

		ready := 0
		if reseedReady(meta, maxAge) {
			ready = 1
		}

		generated, payloads := metrics.BytesGenerated(), metrics.NumWSPayloads()
		// The unsuffixed legacy payload alias stays untyped so counter parsers
		// do not normalize it to the canonical wss_payloads_total a second time.
		values := []struct {
			name, help, kind string
			value            any
		}{
			{"rng_bytes_generated_total", "DRBG bytes generated, including internal child seed derivation", counterType, generated},
			{"rng_mb_generated_total", "Deprecated: generated bytes in whole MiB; use rng_bytes_generated_total", counterType, generated / (1 << 20)},
			{"rng_reseeds_total", "Successful root reseeds across the service", counterType, metrics.Reseeds()},
			{"rng_generator_reseeds_total", "Successful reseeds for this root generator", counterType, meta.ReseedsTotal},
			{"rng_reseed_failures_total", "Failed or skipped reseeds for this root generator", counterType, meta.ReseedFailuresTotal},
			{"rng_reseed_age_seconds", "Seconds since this root generator was seeded", gaugeType, meta.ReseedAge.Seconds()},
			{"rng_reseed_age_ms", "Seed age in milliseconds; prefer rng_reseed_age_seconds", gaugeType, meta.ReseedAge.Milliseconds()},
			{"rng_reseed_last_success_timestamp_seconds", "Unix timestamp of the last successful seed for this root generator", gaugeType, meta.LastReseedAt.Unix()},
			{"rng_ready", "One when this root generator has fresh seed state and no unresolved reseed failure", gaugeType, ready},
			{"http_requests_total", "HTTP requests received, including errors, upgrades, probes and static files", counterType, metrics.NumHTTPRequests()},
			{"wss_payloads_total", "WebSocket messages sent over WS or WSS", counterType, payloads},
			{"wss_payloads", "Deprecated alias of wss_payloads_total", "untyped", payloads},
			{"drbg_instance_count", "Current number of DRBG instances", gaugeType, meta.DRBGInstanceCnt},
			{"qrng_buffer_enabled", "Legacy software QRNG buffer is disabled", gaugeType, 0},
			{"qrng_buffer_bytes", "Legacy software QRNG buffer bytes; disabled", gaugeType, 0},
			{"qrng_buffer_capacity_bytes", "Legacy software QRNG buffer capacity in bytes; disabled", gaugeType, 0},
			{"qrng_buffer_capacity_kb", "Deprecated software buffer capacity in KiB; disabled", gaugeType, 0},
			{"qrng_buffer_capacity_pct", "Deprecated software buffer fill percent; disabled", gaugeType, 0},
			{"entropy_buffer_capacity_kb", "Deprecated software buffer capacity in KiB; disabled", gaugeType, 0},
			{"entropy_buffer_capacity_kb_A", "Deprecated test buffer metric; disabled", gaugeType, 0},
			{"entropy_buffer_capacity_kb_B", "Deprecated test buffer metric; disabled", gaugeType, 0},
		}

		w.Header().Set("Content-Type", "text/plain; version=0.0.4; charset=utf-8")
		w.Header().Set("Cache-Control", "no-store")

		for _, m := range values {
			_, _ = fmt.Fprintf(w, "# HELP %s %s\n# TYPE %s %s\n%s %v\n\n", m.name, m.help, m.name, m.kind, m.name, m.value)
		}
	}
}
