"use strict";

(() => {
    const t = (message, values = {}) => window.EntropyI18n?.t(message, values) ??
        message.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
    function setText(node, message, values = {}) {
        if (window.EntropyI18n) window.EntropyI18n.set(node, message, values);
        else node.textContent = t(message, values);
    }
    const view = document.body.dataset.entropyView;
    const status = document.getElementById("stream-notice");
    const info = document.getElementById("sample-info");
    const scriptURL = document.currentScript.src;
    const endpoint = new URL(view === "colors" ? "/colors" : "/bytes", location.href);
    endpoint.protocol = location.protocol === "https:" ? "wss:" : "ws:";
    endpoint.searchParams.set("format", view === "colors" ? "hash" : "compact");

    // Omitted settings retain the server's defaults. Preserve duplicate values
    // so server validation can reject ambiguous input rather than hiding it.
    const query = new URLSearchParams(location.search);
    for (const name of ["bytes", "refresh"]) {
        for (const value of query.getAll(name)) endpoint.searchParams.append(name, value);
    }

    let worker = null;
    let displayClock = null;

    function setStatus(state, message) {
        status.hidden = false;
        status.dataset.state = state;
        setText(status, message);
    }

    function start() {
        setStatus("waiting", "Awaiting first sample");
        const active = new Worker(new URL("entropy-display-worker.js", scriptURL));
        worker = active;
        active.onerror = () => {
            if (worker === active) setStatus("error", "Display worker failed");
        };
        displayClock = window.EntropyDisplayClock.create(frame => {
            if (worker !== active) return;
            status.hidden = true;
            // Two rows preserve all 32 SHA-256 digest bytes.
            document.getElementById("hash").textContent = view === "colors" &&
                /^[a-fA-F0-9]{64}$/.test(frame.hash) ?
                frame.hash.slice(0, 32) + "\n" + frame.hash.slice(32) : frame.hash;
            const color = [0, 2, 4].map(offset => parseInt(frame.hash.slice(offset, offset + 2), 16) / 2);
            if (view === "colors") {
                const swatch = document.getElementById("hash");
                swatch.style.backgroundColor = `rgb(${color.join(",")})`;
                const linear = color.map(channel => {
                    const value = channel / 255;
                    return value <= .04045 ? value / 12.92 : ((value + .055) / 1.055) ** 2.4;
                });
                const luminance = .2126 * linear[0] + .7152 * linear[1] + .0722 * linear[2];
                swatch.style.color = luminance > .179 ? "#000" : "#fff";
            }
            if (view === "bytes") {
                document.getElementById("hex").textContent = frame.hex;
                document.getElementById("base64").textContent = frame.base64;
                setText(info, "{bytes} bytes received; showing {previewBytes} bytes. SHA-256 covers the full sample.", {bytes: frame.bytes, previewBytes: frame.previewBytes});
            } else {
                setText(info, "Colour derived from SHA-256 of {bytes} generated bytes.", {bytes: frame.bytes});
            }
            active.postMessage({ type: "ready" });
        });
        active.onmessage = function(event) {
            if (worker !== active) return;
            const frame = event.data;
            if (frame.type === "status") {
                setStatus(frame.state || "error", frame.text);
                return;
            }
            if (frame.type !== "frame") return;

            displayClock.submit(frame);
        };
        active.postMessage({ type: "start", view, url: endpoint.href });
    }

    window.addEventListener("pagehide", () => {
        if (worker !== null) worker.postMessage({ type: "stop" });
        worker = null;
        displayClock?.cancel();
        displayClock = null;
    });
    window.addEventListener("pageshow", event => {
        if (event.persisted) start();
    });
    start();
})();
